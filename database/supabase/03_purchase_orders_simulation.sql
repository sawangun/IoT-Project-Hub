-- Jalankan sekali di Supabase SQL Editor untuk mengaktifkan checkout & simulasi pembayaran.
-- Status paid pada file ini berarti LUNAS SIMULASI, bukan transaksi uang sungguhan.

create table if not exists public.purchase_orders (
    id bigint generated by default as identity primary key,
    user_id uuid null references public.profiles(id) on delete set null,
    customer_name varchar(120) not null,
    customer_email varchar(160) not null,
    customer_phone varchar(30) not null,
    item_type varchar(20) not null check (item_type in ('kit', 'component')),
    item_id bigint not null,
    item_name varchar(255) not null,
    quantity integer not null check (quantity between 1 and 20),
    unit_price numeric(14,2) not null check (unit_price >= 0),
    subtotal numeric(14,2) not null check (subtotal >= 0),
    total numeric(14,2) not null check (total >= 0),
    payment_method varchar(30) not null check (payment_method in ('qris', 'edupay', 'virtual_account')),
    status varchar(30) not null default 'pending' check (status in ('pending', 'paid', 'processing', 'completed', 'cancelled')),
    notes text null,
    paid_at timestamptz null,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create index if not exists purchase_orders_user_created_idx
    on public.purchase_orders (user_id, created_at desc);

